let currentLang = 'en';
let currentStep = 0;
let journeyTimer = null;

const $ = (selector) => document.querySelector(selector);
const $$ = (selector) => Array.from(document.querySelectorAll(selector));

function applyLanguage() {
  const dict = translations[currentLang];
  document.documentElement.lang = currentLang;
  $('#langToggle').textContent = currentLang === 'en' ? 'TR' : 'EN';
  $$('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) el.textContent = dict[key];
  });
  $$('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) el.placeholder = dict[key];
  });
  renderSteps();
  renderTeam();
  renderMedia();
  renderSupporters();
  updateStage(currentStep);
}

function renderSteps() {
  const container = $('#stepsList');
  container.innerHTML = '';
  labSteps[currentLang].forEach(([title, desc], index) => {
    const item = document.createElement('button');
    item.type = 'button';
    item.className = `step-item ${index === currentStep ? 'active' : ''}`;
    item.innerHTML = `<strong>${index + 1}. ${title}</strong><p>${desc}</p>`;
    item.addEventListener('click', () => {
      stopJourney();
      currentStep = index;
      updateStage(currentStep);
    });
    container.appendChild(item);
  });
}

function renderTeam() {
  const grid = $('#teamGrid');
  grid.innerHTML = '';
  team[currentLang].forEach(member => {
    const card = document.createElement('article');
    card.className = `team-card reveal visible ${member.founder ? 'founder' : ''}`;
    card.innerHTML = `
      <div class="member-photo">
        <img src="${member.photo}" alt="${member.name}" onerror="this.style.display='none'; this.parentElement.textContent='${member.icon}'">
      </div>
      <span class="role-pill">${member.role}</span>
      <h3>${member.name}</h3>
      <p>${member.bio}</p>
      <button class="btn btn-secondary" type="button">${translations[currentLang].viewBio}</button>
    `;
    card.querySelector('button').addEventListener('click', () => openMemberModal(member));
    grid.appendChild(card);
  });
}

function openMemberModal(member) {
  $('#modalName').textContent = member.name;
  $('#modalRole').textContent = member.role;
  $('#modalStatus').textContent = member.status;
  $('#modalPhoto').textContent = member.icon;
  $('#modalBioText').textContent = member.bio;
  $('#modalContributionText').textContent = member.contribution;
  $('#memberModal').classList.add('open');
  $('#memberModal').setAttribute('aria-hidden', 'false');
}

function closeMemberModal() {
  $('#memberModal').classList.remove('open');
  $('#memberModal').setAttribute('aria-hidden', 'true');
}

function renderMedia() {
  const grid = $('#mediaGrid');
  grid.innerHTML = '';
  media[currentLang].forEach(([publisher, title, desc, link, category]) => {
    const card = document.createElement('article');
    card.className = 'media-card reveal visible';
    card.innerHTML = `
      <span class="category">${category}</span>
      <h3>${title}</h3>
      <p><strong>${publisher}</strong></p>
      <p>${desc}</p>
      <a href="${link}" target="_blank" rel="noopener noreferrer">${translations[currentLang].readMore}</a>
    `;
    grid.appendChild(card);
  });
}

